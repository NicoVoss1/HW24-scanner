-- Additive, read-only view. Only verified receiver fields and allowlisted scalar raw fields.
CREATE SQL SECURITY DEFINER VIEW hw24_hub_history_extended AS
SELECT a.source_id,a.jtl_article_id,
 a.han,
 a.asin,
 a.kurzbeschreibung,
 a.beschreibung,
 a.seo_titel,
 a.seo_beschreibung,
 a.netto_vk,
 a.netto_ek,
 a.letzter_ek,
 a.letzter_ek_datum,
 a.amazon_vk,
 a.ebay_preis,
 a.source_modified_at,
 NULLIF(JSON_UNQUOTE(JSON_EXTRACT(IF(JSON_VALID(a.raw_json),a.raw_json,'{}'),'$.cAnmerkung')),'null') AS cAnmerkung,
 NULLIF(JSON_UNQUOTE(JSON_EXTRACT(IF(JSON_VALID(a.raw_json),a.raw_json,'{}'),'$.cAktiv')),'null') AS cAktiv,
 NULLIF(JSON_UNQUOTE(JSON_EXTRACT(IF(JSON_VALID(a.raw_json),a.raw_json,'{}'),'$.nBearbeitungszeit')),'null') AS nBearbeitungszeit,
 NULLIF(JSON_UNQUOTE(JSON_EXTRACT(IF(JSON_VALID(a.raw_json),a.raw_json,'{}'),'$.nAutomatischeLiefertageberechnung')),'null') AS nAutomatischeLiefertageberechnung,
 NULLIF(JSON_UNQUOTE(JSON_EXTRACT(IF(JSON_VALID(a.raw_json),a.raw_json,'{}'),'$.cTopArtikel')),'null') AS cTopArtikel,
 NULLIF(JSON_UNQUOTE(JSON_EXTRACT(IF(JSON_VALID(a.raw_json),a.raw_json,'{}'),'$.cNeu')),'null') AS cNeu,
 NULLIF(JSON_UNQUOTE(JSON_EXTRACT(IF(JSON_VALID(a.raw_json),a.raw_json,'{}'),'$.dMod')),'null') AS dMod,
 NULLIF(JSON_UNQUOTE(JSON_EXTRACT(IF(JSON_VALID(a.raw_json),a.raw_json,'{}'),'$.dErstelldatum')),'null') AS dErstelldatum,
 NULLIF(JSON_UNQUOTE(JSON_EXTRACT(IF(JSON_VALID(a.raw_json),a.raw_json,'{}'),'$.kBenutzerLetzteAenderung')),'null') AS kBenutzerLetzteAenderung,
 NULLIF(JSON_UNQUOTE(JSON_EXTRACT(IF(JSON_VALID(a.raw_json),a.raw_json,'{}'),'$.nMHD')),'null') AS nMHD,
 NULLIF(JSON_UNQUOTE(JSON_EXTRACT(IF(JSON_VALID(a.raw_json),a.raw_json,'{}'),'$.nDelete')),'null') AS nDelete,
 CASE WHEN s.rows_type='ARRAY' AND s.row_count=1 AND (s.truncated_flag IS NULL OR s.truncated_flag IN ('false','0')) THEN s.total_stock ELSE NULL END AS total_stock,
 CASE WHEN s.rows_type='ARRAY' AND s.row_count=1 AND (s.truncated_flag IS NULL OR s.truncated_flag IN ('false','0')) THEN s.available_stock ELSE NULL END AS available_stock,
 CASE WHEN s.rows_type='ARRAY' AND s.row_count=1 AND (s.truncated_flag IS NULL OR s.truncated_flag IN ('false','0')) THEN s.in_orders ELSE NULL END AS in_orders,
 CASE WHEN s.rows_type='ARRAY' AND s.row_count=1 AND (s.truncated_flag IS NULL OR s.truncated_flag IN ('false','0')) THEN s.incoming ELSE NULL END AS incoming
FROM hw24_jtl_articles a LEFT JOIN hw24_hub_stock_source s ON s.source_id=a.source_id AND s.jtl_article_id=a.jtl_article_id;
